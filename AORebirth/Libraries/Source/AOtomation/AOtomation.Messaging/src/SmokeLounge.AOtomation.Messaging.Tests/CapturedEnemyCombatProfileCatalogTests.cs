        private static int FindUnknownSource(IEnumerable<int> capturedSources)
        {
            var occupied = new HashSet<int>(capturedSources);
            int candidate = unchecked((int)0x7F000001);
            while (occupied.Contains(candidate))
            {
                candidate++;
            }

            return candidate;
        }

        private static int FindUnknownLevel(
            CapturedEnemyCombatProfileDefinition profile,
            IEnumerable<CapturedEnemyCombatProfileDefinition> profiles)
        {
            var occupied = new HashSet<int>(
                profiles.Where(
                    value => value.ResourceId == profile.ResourceId
                             && value.MonsterData == profile.MonsterData
                             && string.Equals(value.Name, profile.Name, StringComparison.Ordinal))
                    .Select(value => value.Level));
            int candidate = 1;
            while (occupied.Contains(candidate))
            {
                candidate++;
            }

            return candidate;
        }

