        private static HashSet<string> ReadInventoryMetadataBindings(string path)
        {
            string json = File.ReadAllText(path);
            Dictionary<int, int> realmMap = ReadCapturedRealmMap(ReadInventoryHeader(path));
            var result = new HashSet<string>(StringComparer.Ordinal);
            foreach (string metadata in ReadJsonArrayObjects(json, "metadataGenerations"))
            {
                int capturedRealmId = ReadJsonInt(metadata, "capturedRealmId");
                int resourceId;
                if (!realmMap.TryGetValue(capturedRealmId, out resourceId))
                {
                    continue;
                }

                string sourceIdentity = ReadJsonString(metadata, "sourceIdentity");
                uint parsedSource;
                if (!sourceIdentity.StartsWith("0x", StringComparison.Ordinal)
                    || !uint.TryParse(
                        sourceIdentity.Substring(2),
                        System.Globalization.NumberStyles.HexNumber,
                        System.Globalization.CultureInfo.InvariantCulture,
                        out parsedSource))
                {
                    continue;
                }

                result.Add(
                    ExactBindingKey(
                        resourceId,
                        ReadJsonString(metadata, "name"),
                        ReadJsonInt(metadata, "monsterData"),
                        ReadJsonInt(metadata, "level"),
                        unchecked((int)parsedSource)));
            }

            return result;
        }

        private static Dictionary<int, int> ReadCapturedRealmMap(string inventoryHeader)
        {
            int name = inventoryHeader.IndexOf(
                "\"capturedRealmToRuntimeResource\"",
                StringComparison.Ordinal);
            Assert.IsTrue(name >= 0);
            int start = inventoryHeader.IndexOf('{', name);
            int end = inventoryHeader.IndexOf('}', start);
            Assert.IsTrue(start >= 0 && end > start);
            string mapJson = inventoryHeader.Substring(start, end - start + 1);
            var result = new Dictionary<int, int>();
            foreach (Match match in Regex.Matches(
                mapJson,
                "\\\"(?<realm>[0-9]+)\\\"\\s*:\\s*(?<resource>[0-9]+)",
                RegexOptions.CultureInvariant))
            {
                result.Add(
                    int.Parse(match.Groups["realm"].Value),
                    int.Parse(match.Groups["resource"].Value));
            }

            Assert.IsTrue(result.Count > 0);
            return result;
        }

