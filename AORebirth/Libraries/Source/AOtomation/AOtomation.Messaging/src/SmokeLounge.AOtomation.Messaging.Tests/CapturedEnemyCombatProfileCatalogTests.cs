                        0,
                        0,
                        0,
                        0,
                        0));
            CapturedEnemyCombatProfileDefinition oneStream = CreateSpecializedTestProfile(
                CreateSpecializedTestStream(10, 2.0d, 1.0d));
            Assert.IsFalse(
                oneStream.MatchesSpecialized(parallelContract),
                "One raw stream must not certify two specialized phases.");

            CapturedEnemyCombatAttackDefinition opening = CreateSpecializedTestAttack(10, 2.0d);
            CapturedEnemyCombatAttackDefinition repeating = CreateSpecializedTestAttack(20, 3.0d);
            CapturedEnemyCombatContract contract = CreateSpecializedTestContract(
                1.0d,
                opening,
                repeating);

            CapturedEnemyCombatProfileDefinition wrongRepeatingFirstHit =
                CreateSpecializedTestProfile(
                    CreateSpecializedTestStream(10, 2.0d, 1.0d),
                    CreateSpecializedTestStream(20, 3.0d, 99.0d));
            Assert.IsFalse(
                wrongRepeatingFirstHit.MatchesSpecialized(contract),
                "Repeating first-hit evidence must not be bypassed.");

            CapturedEnemyCombatProfileDefinition exactBijection = CreateSpecializedTestProfile(
                CreateSpecializedTestStream(10, 2.0d, 1.0d),
                CreateSpecializedTestStream(20, 3.0d, 3.0d));
            Assert.IsTrue(exactBijection.MatchesSpecialized(contract));

            CapturedEnemyCombatProfileDefinition runtimeUnsafe =
                CreateSpecializedTestProfileWithRuntimeSafety(
                    false,
                    CreateSpecializedTestStream(10, 2.0d, 1.0d),
                    CreateSpecializedTestStream(20, 3.0d, 3.0d));
            Assert.IsFalse(
                runtimeUnsafe.MatchesSpecialized(contract),
                "A stream rejected by capture extraction must not certify a specialized runtime.");
