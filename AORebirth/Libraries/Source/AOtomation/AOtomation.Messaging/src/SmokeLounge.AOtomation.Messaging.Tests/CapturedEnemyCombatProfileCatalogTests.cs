                "Capture certification must enrich a clone instead of mutating the existing contract.");
            CollectionAssert.DoesNotContain(
                enriched.ParallelAttackSequence.Streams[0].Attack.CapturedDamageObservations,
                11,
                "Runtime replay must not synthesize an uncaptured value inside the observed envelope.");

            CapturedEnemyCombatAttackDefinition attackInfoMismatch = CreateSpecializedTestAttack(
                10,
                12,
                2.0d,
                9.5d,
                99);
            CapturedEnemyCombatContract mismatchedContract =
                CapturedEnemyCombatContract.CapturedParallelAttackSequence(
                    "specialized packet mismatch test",
                    new CapturedEnemyParallelAttackSequenceDefinition(
                        new[]
                        {
                            new CapturedEnemyParallelAttackStreamDefinition(
                                1.0d,
                                attackInfoMismatch)
                        },
                        new CapturedEnemySpecialAttackDefinition[0],
                        0,
                        0,
                        0,
                        0,
                        0,
                        0,
                        0,
                        0));
            Assert.IsFalse(profile.TryEnrichSpecialized(mismatchedContract, out enriched));
            Assert.IsNull(enriched);
        }

