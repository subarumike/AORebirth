            var failures = new List<string>();
            int certified = 0;
            int quarantined = 0;
            int subwayCertified = 0;
            int subwayQuarantined = 0;
            int templeCertified = 0;
            int templeQuarantined = 0;

            Assert.AreEqual(322, spawns.Count(value => value.PlayfieldInstance == 127));
            Assert.AreEqual(153, spawns.Count(value => value.PlayfieldInstance == 1931));
            foreach (OrdinaryEnemySpawnDefinition spawn in spawns)
            {
                OrdinaryEnemyProfile profile = profiles[spawn.ProfileKey];
                CapturedEnemyCombatContract baseline = profile.Combat.ResolveContract(
                    spawn.SourceIdentity,
                    spawn.Level);
                baseline.Retaliates = true;
                baseline.AiProfile = ZoneEngine.Core.NpcAiProfile.Passive;
                CapturedEnemyCombatContract resolved;
                string failure;
                bool success = CapturedEnemyCombatProfileCatalog.TryResolve(
                    spawn.PlayfieldInstance,
                    profile.DisplayName,
                    profile.MonsterData,
                    spawn.Level,
                    spawn.SourceIdentity,
                    baseline,
                    out resolved,
                    out failure);
                if (success)
                {
                    certified++;
                    if (spawn.PlayfieldInstance == 127) subwayCertified++;
                    else templeCertified++;
                    Assert.IsTrue(resolved.IsCombatReady);
                    CapturedEnemyCombatProfileDefinition[] keyMatches = generatedProfiles.Where(
                        value => value.MatchesKey(
                            spawn.PlayfieldInstance,
                            profile.DisplayName,
                            profile.MonsterData,
                            spawn.Level)).ToArray();
                    CapturedEnemyCombatProfileDefinition[] evidenceMatches = keyMatches.Where(
                        value => value.ContainsSource(
                            resolved.EvidenceSourceIdentity)).ToArray();
                    CapturedEnemyCombatProfileDefinition[] compatibleKeyMatches =
                        keyMatches.Where(value => value.CaptureRuntimeEvidenceSafe).ToArray();
                    Assert.AreEqual(1, evidenceMatches.Length);
                    if (compatibleKeyMatches.Any(
                            value => value.ContainsSource(spawn.SourceIdentity)))
                    {
                        Assert.AreEqual(spawn.SourceIdentity, resolved.EvidenceSourceIdentity);
                    }
                    else
                    {
                        Assert.AreEqual(1, compatibleKeyMatches.Length);
                        Assert.AreEqual(
                            evidenceMatches[0].RepresentativeEvidenceSourceIdentity,
                            resolved.EvidenceSourceIdentity);
                    }
                }
                else
                {
                    quarantined++;
                    if (spawn.PlayfieldInstance == 127) subwayQuarantined++;
                    else templeQuarantined++;
                    Assert.IsFalse(string.IsNullOrWhiteSpace(failure));
                    Assert.IsTrue(
                        HasExactInventoryRecord(
                            inventoryProfiles,
                            spawn.PlayfieldInstance,
                            profile.DisplayName,
                            profile.MonsterData,
                            spawn.Level,
                            spawn.SourceIdentity)
                        || inventoryMetadataBindings.Contains(
                            ExactBindingKey(
                                spawn.PlayfieldInstance,
                                profile.DisplayName,
                                profile.MonsterData,
                                spawn.Level,
                                spawn.SourceIdentity)),
                        "Active binding lacks an exact corpus-backed unresolved record: resource="
                        + spawn.PlayfieldInstance
                        + " name=" + profile.DisplayName
                        + " md=" + profile.MonsterData
                        + " level=" + spawn.Level
                        + " source=" + spawn.SourceIdentity.ToString("X8")
                        + " reason=" + failure);
                    failures.Add(
                        spawn.SpawnKey
                        + " source=" + spawn.SourceIdentity.ToString("X8")
                        + " name=" + profile.DisplayName
                        + " md=" + profile.MonsterData
                        + " level=" + spawn.Level
                        + ": " + failure);
                }
            }

            Assert.AreEqual(spawns.Length, certified + quarantined);
            Assert.IsTrue(
                certified > 15,
                "The generated corpus did not improve active dungeon certification beyond the seed audit. "
                + string.Join(" | ", failures.Take(5).ToArray()));
            this.TestContext.WriteLine(
                "PF127 certified={0} quarantined={1}; PF1931 certified={2} quarantined={3}; total certified={4} quarantined={5}",
                subwayCertified,
                subwayQuarantined,
                templeCertified,
                templeQuarantined,
                certified,
                quarantined);
        }

