        {
            string root = FindRepositoryRoot();
            Dictionary<string, string> inventoryProfiles = ReadInventoryProfiles(
                Path.Combine(
                    root,
                    "docs",
                    "generated",
                    "capture_backed_npc_combat_inventory.json"));
