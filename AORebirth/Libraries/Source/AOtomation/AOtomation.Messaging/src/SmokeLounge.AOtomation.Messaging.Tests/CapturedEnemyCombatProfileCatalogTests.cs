                    ambiguousRepresentative.ResourceId,
                    ambiguousRepresentative.Name,
                    ambiguousRepresentative.MonsterData,
                    ambiguousRepresentative.Level,
                    0,
                    CapturedEnemyCombatContract.Unresolved("test baseline", true),
