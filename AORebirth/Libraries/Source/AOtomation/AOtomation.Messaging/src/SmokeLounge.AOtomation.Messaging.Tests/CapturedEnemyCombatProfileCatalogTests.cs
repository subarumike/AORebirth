                ambiguousRuntimeInitialization.MatchesSpecialized(contract),
                "Mutable WIFU/SAW initialization must be deterministic before runtime enrichment.");
        }

        [TestMethod]
        public void SpecializedMatchingEnrichesNoncontinuousDamageInCapturedOrderAndFailsClosedOnAttackInfoMismatch()
        {
            CapturedEnemyCombatAttackDefinition attack = CreateSpecializedTestAttack(
                10,
                12,
                2.0d,
                9.5d,
                0);
            CapturedEnemyCombatContract contract =
                CapturedEnemyCombatContract.CapturedParallelAttackSequence(
                    "noncontinuous specialized replay test",
                    new CapturedEnemyParallelAttackSequenceDefinition(
                        new[]
                        {
                            new CapturedEnemyParallelAttackStreamDefinition(1.0d, attack)
                        },
                        new CapturedEnemySpecialAttackDefinition[0],
                        0,
                        0,
                        0,
                        0,
                        0,
                        0,
                        0,
                        0));
            int[] orderedDamageObservations = { 10, 12, 10, 12 };
            CapturedEnemyCombatProfileStreamDefinition fixedReplayStream =
                CreateSpecializedTestStream(
                    10,
                    12,
                    orderedDamageObservations,
                    2.0d,
                    1.0d,
                    9.5d);
            Assert.IsTrue(
                fixedReplayStream.Matches(
                    attack,
                    0.0d,
                    1.0d,
                    new[] { 2.0d },
                    null),
                "A fixed replay backed by ordered observations must not require every integer in the damage envelope.");
            CapturedEnemyCombatProfileDefinition missingRangeProfile = CreateSpecializedTestProfile(
                CreateSpecializedTestStream(
                    10,
                    12,
                    orderedDamageObservations,
                    2.0d,
                    1.0d,
                    null));

            CapturedEnemyCombatContract enriched;
            Assert.IsTrue(
                missingRangeProfile.TryEnrichSpecialized(contract, out enriched),
                "Packet matching must not reject an otherwise exact stream because range behavior is owned independently.");
            Assert.IsNotNull(enriched);
            Assert.AreEqual(
                9.5d,
                enriched.ParallelAttackSequence.Streams[0].Attack.Range,
                "Packet enrichment must preserve the existing runtime range owner without claiming captured range evidence.");

            CapturedEnemyCombatProfileDefinition profile = CreateSpecializedTestProfile(
                CreateSpecializedTestStream(
                    10,
                    12,
                    orderedDamageObservations,
                    2.0d,
                    1.0d,
                    9.5d));
            Assert.IsTrue(profile.TryEnrichSpecialized(contract, out enriched));
            Assert.IsNotNull(enriched);
            CollectionAssert.AreEqual(
                orderedDamageObservations,
                enriched.ParallelAttackSequence.Streams[0].Attack.CapturedDamageObservations);
            Assert.AreEqual(9.5d, enriched.ParallelAttackSequence.Streams[0].Attack.Range);
