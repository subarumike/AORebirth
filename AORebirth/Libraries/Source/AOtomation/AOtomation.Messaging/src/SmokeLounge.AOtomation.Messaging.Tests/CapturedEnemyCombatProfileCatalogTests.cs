                                familyMatches.All(
                                    value =>
                                        familyMatches[0]
                                            .MatchesCaptureProvenEquippedWeaponArchetype(
                                                value)));
                        }

                        Assert.IsTrue(
                            familyMatches.Any(
                                value => value.ContainsSource(
                                    resolved.EvidenceSourceIdentity)));
                    }
                    else
                    {
                        CapturedEnemyCombatProfileDefinition[] keyMatches =
