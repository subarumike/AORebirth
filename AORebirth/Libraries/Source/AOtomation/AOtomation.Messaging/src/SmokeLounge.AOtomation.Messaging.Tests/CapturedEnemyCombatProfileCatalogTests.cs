                CapturedEnemyCombatProfileCatalog.TryResolve(
                    uniqueCompatibleRepresentative.ResourceId,
                    uniqueCompatibleRepresentative.Name,
                    uniqueCompatibleRepresentative.MonsterData,
                    uniqueCompatibleRepresentative.Level,
