        [TestMethod]
        public void GeneratedCatalogMatchesTheVersionedInventoryAndFailsClosedOnAmbiguousExactBindings()
        {
            string root = FindRepositoryRoot();
            string inventoryPath = Path.Combine(
                root,
                "docs",
                "generated",
                "capture_backed_npc_combat_inventory.json");
            string generatedPath = Path.Combine(
                root,
                "AORebirth",
                "Server",
                "ZoneEngine",
                "Core",
                "Playfields",
                "CapturedEnemyCombatProfileCatalog.g.cs");
            string inventoryHeader = ReadInventoryHeader(inventoryPath);
            CapturedEnemyCombatProfileDefinition[] profiles =
                CapturedEnemyCombatProfileCatalog.GetProfilesForTests();

            Assert.IsTrue(File.Exists(generatedPath));
            Assert.IsTrue(File.ReadAllText(generatedPath).StartsWith("// <auto-generated />"));
            Assert.AreEqual(3, ReadSummaryValue(inventoryHeader, "schemaVersion"));
            Assert.AreEqual(
                0,
                ReadSummaryValue(inventoryHeader, "recoverableEvidenceBlockers"),
                "No complete normal raw chain may remain unintegrated without a documented exclusion.");
            Assert.AreEqual(
                profiles.Length,
                ReadRuntimeGeneratedDefinitionCount(inventoryHeader));
            Assert.AreEqual(
                ReadRuntimeGeneratedDefinitionCount(inventoryHeader),
                CapturedEnemyCombatGeneratedPacketFixtures.Create().Length,
                "Every generated capture-certified inventory variant must have an exact-byte fixture.");
            Assert.IsTrue(profiles.Length > 15, "The generated catalog must supersede the 15-profile seed audit.");
            Assert.AreEqual(
                profiles.Length,
                profiles.Select(value => value.ProfileId).Distinct(StringComparer.Ordinal).Count());

            foreach (CapturedEnemyCombatProfileDefinition profile in profiles)
            {
                Assert.IsFalse(string.IsNullOrWhiteSpace(profile.ProfileId));
                Assert.IsFalse(string.IsNullOrWhiteSpace(profile.Evidence));
                Assert.IsTrue(profile.ResourceId > 0);
                Assert.IsFalse(string.IsNullOrWhiteSpace(profile.Name));
                Assert.IsTrue(profile.MonsterData > 0);
                Assert.IsTrue(profile.Level > 0);
                Assert.IsTrue(profile.SourceIdentities.Length > 0);
                Assert.AreEqual(
                    profile.SourceIdentities.Length,
                    profile.SourceIdentities.Distinct().Count(),
                    profile.ProfileId + " repeats a captured source identity.");
                Assert.IsTrue(profile.SourceIdentities.All(value => value != 0));
                CollectionAssert.Contains(
                    profile.SourceIdentities,
                    profile.RepresentativeEvidenceSourceIdentity);
                Assert.IsTrue(profile.Streams.Length > 0);

                if (profile.WeaponDefinition != null)
                {
                    Assert.IsTrue(
                        profile.WeaponDefinition.IsValid,
                        profile.ProfileId + " generated an invalid WIFU definition.");
                    CollectionAssert.Contains(
                        profile.SourceIdentities,
                        profile.WeaponDefinition.EvidenceSourceIdentity);
                }

                foreach (CapturedEnemyCombatProfileStreamDefinition stream in profile.Streams)
                {
                    Assert.IsTrue(stream.MinimumObservedDamage > 0);
                    Assert.IsTrue(stream.MaximumObservedDamage >= stream.MinimumObservedDamage);
                    Assert.IsTrue(stream.InitialAmmoCount >= -1);
                    Assert.AreEqual(3, stream.HitTypeWire);
                    Assert.IsTrue(stream.ObservedRechargeSeconds >= 0);
                    if (stream.WeaponSlot == 6 && stream.WeaponInstance == 0)
                    {
                        Assert.IsNotNull(
                            profile.WeaponDefinition,
                            profile.ProfileId + " uses the right-hand weapon slot without an owner-linked WIFU.");
                    }
                }
            }

            var exactBindings = profiles.SelectMany(
                profile => profile.SourceIdentities.Select(
                    source => new
                    {
                        Key = ExactBindingKey(profile, source),
                        Profile = profile,
                        SourceIdentity = source
                    })).ToArray();
            var ambiguousExactBindings = exactBindings
                .GroupBy(value => value.Key, StringComparer.Ordinal)
                .Where(group => group.Count() > 1)
                .ToArray();
            foreach (var ambiguousBinding in ambiguousExactBindings)
            {
                Assert.AreEqual(
                    ambiguousBinding.Count(),
                    ambiguousBinding.Select(value => value.Profile.ProfileId)
                        .Distinct(StringComparer.Ordinal)
                        .Count(),
                    "A duplicate exact binding repeated one generated packet variant.");
                Assert.IsTrue(
                    ambiguousBinding.All(value => !value.Profile.SemanticFallbackCaptureProven),
                    "An ambiguous exact binding must not claim a source-free fallback.");

                var representative = ambiguousBinding.First();
                CapturedEnemyCombatContract ambiguousResolved;
                string ambiguousFailure;
                Assert.IsFalse(
                    CapturedEnemyCombatProfileCatalog.TryResolve(
                        representative.Profile.ResourceId,
                        representative.Profile.Name,
                        representative.Profile.MonsterData,
                        representative.Profile.Level,
                        representative.SourceIdentity,
                        CapturedEnemyCombatContract.Unresolved("ambiguous exact binding", true),
                        out ambiguousResolved,
                        out ambiguousFailure),
                    "Capture-distinct variants sharing one source must fail closed.");
                Assert.IsFalse(ambiguousResolved.IsCombatReady);
                Assert.IsTrue(
                    ambiguousFailure.IndexOf(
                        "does not distinguish",
                        StringComparison.Ordinal) >= 0
                    || ambiguousFailure.IndexOf(
                        "explicitly unsafe",
                        StringComparison.Ordinal) >= 0,
                    ambiguousFailure);
            }

            Assert.IsFalse(
                profiles.Where(value => value.SemanticFallbackCaptureProven)
                    .GroupBy(SemanticKey, StringComparer.Ordinal)
                    .Any(group => group.Count() != 1),
                "More than one generated packet variant claims the same source-free semantic fallback.");

        }

        [TestMethod]
        public void InventoryDecodeErrorsAreExplicitAndNeverReusedAsMetadataProvenance()
        {
            string inventoryPath = Path.Combine(
                FindRepositoryRoot(),
                "docs",
                "generated",
                "capture_backed_npc_combat_inventory.json");
            string inventoryHeader = ReadInventoryHeader(inventoryPath);
            string inventoryJson = File.ReadAllText(inventoryPath);
            List<string> decodeErrors = ReadJsonArrayObjects(
                inventoryJson,
                "decodeOrProjectionErrors");
            Assert.AreEqual(
                ReadSummaryValue(inventoryHeader, "decodeOrProjectionErrors"),
                decodeErrors.Count);
            var metadataKeys = new HashSet<string>(
                ReadJsonArrayObjects(inventoryJson, "metadataGenerations").Select(
                    value => ReadJsonString(value, "capture")
                             + "|" + ReadJsonInt(value, "sequence")),
                StringComparer.Ordinal);
            foreach (string decodeError in decodeErrors)
            {
                string capture = ReadJsonString(decodeError, "capture");
                string artifact = ReadJsonString(decodeError, "artifact");
                int sequence = ReadJsonInt(decodeError, "sequence");
                string error = ReadJsonString(decodeError, "error");
                Assert.IsFalse(string.IsNullOrWhiteSpace(capture));
                Assert.IsFalse(string.IsNullOrWhiteSpace(artifact));
                Assert.IsTrue(sequence > 0);
                Assert.IsFalse(string.IsNullOrWhiteSpace(error));
                Assert.IsFalse(
                    metadataKeys.Contains(capture + "|" + sequence),
                    "An undecoded raw SCFU was reused as metadata provenance: "
                    + capture + " sequence=" + sequence);
            }
        }

