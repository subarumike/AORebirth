                    "bijective matching test",
                    new CapturedEnemyParallelAttackSequenceDefinition(
                        new[]
                        {
                            new CapturedEnemyParallelAttackStreamDefinition(1.0d, duplicatePhase),
                            new CapturedEnemyParallelAttackStreamDefinition(1.0d, duplicatePhase)
