        private static List<string> ReadJsonArrayObjects(string json, string arrayName)
        {
            Match arrayMember = Regex.Match(
                json,
                "\\\"" + Regex.Escape(arrayName) + "\\\"\\s*:\\s*\\[",
                RegexOptions.CultureInvariant);
            Assert.IsTrue(arrayMember.Success, "Inventory is missing the " + arrayName + " array.");
            int arrayStart = json.IndexOf('[', arrayMember.Index);
            var result = new List<string>();
            bool inString = false;
            bool escaping = false;
            int objectDepth = 0;
            int objectStart = -1;
            for (int index = arrayStart + 1; index < json.Length; index++)
            {
                char value = json[index];
                if (inString)
                {
                    if (escaping)
                    {
                        escaping = false;
                    }
                    else if (value == '\\')
                    {
                        escaping = true;
                    }
                    else if (value == '"')
                    {
                        inString = false;
                    }

                    continue;
                }

                if (value == '"')
                {
                    inString = true;
                    continue;
                }

                if (value == '{')
                {
                    if (objectDepth == 0)
                    {
                        objectStart = index;
                    }

                    objectDepth++;
                    continue;
                }

                if (value == '}')
                {
                    objectDepth--;
                    Assert.IsTrue(objectDepth >= 0, "Inventory profiles JSON is unbalanced.");
                    if (objectDepth == 0 && objectStart >= 0)
                    {
                        result.Add(json.Substring(objectStart, index - objectStart + 1));
                        objectStart = -1;
                    }

                    continue;
                }

                if (value == ']' && objectDepth == 0)
                {
                    break;
                }
            }

            return result;
        }

        private static string ReadJsonString(string jsonObject, string name)
        {
            Match match = Regex.Match(
                jsonObject,
                "\\\"" + Regex.Escape(name)
                + "\\\"\\s*:\\s*\\\"(?<value>(?:\\\\.|[^\\\"])*)\\\"",
                RegexOptions.CultureInvariant);
            Assert.IsTrue(match.Success, "JSON record is missing string field " + name + ".");
            return Regex.Unescape(match.Groups["value"].Value);
        }

        private static int ReadJsonInt(string jsonObject, string name)
        {
            Match match = Regex.Match(
                jsonObject,
                "\\\"" + Regex.Escape(name) + "\\\"\\s*:\\s*(?<value>-?[0-9]+)",
                RegexOptions.CultureInvariant);
            Assert.IsTrue(match.Success, "JSON record is missing integer field " + name + ".");
            return int.Parse(match.Groups["value"].Value);
        }

        private static string ReadInventoryHeader(string path)
        {
            var header = new StringBuilder();
            using (var reader = new StreamReader(path))
            {
                string line;
                while ((line = reader.ReadLine()) != null)
                {
                    if (line.TrimStart().StartsWith("\"sessions\"", StringComparison.Ordinal))
                    {
                        break;
                    }

                    header.AppendLine(line);
                }
            }

            return header.ToString();
        }

        private static int ReadSummaryValue(string inventoryHeader, string name)
        {
            Match match = Regex.Match(
                inventoryHeader,
                "\\\"" + Regex.Escape(name) + "\\\"\\s*:\\s*(?<value>-?[0-9]+)",
                RegexOptions.CultureInvariant);
            Assert.IsTrue(match.Success, "Inventory header is missing " + name + ".");
            return int.Parse(match.Groups["value"].Value);
        }

