"""Writes src/playfield_names.inc from AORebirth/GameData/Playfields/*/metadata.json (playfieldName, read from the
client's own playfield records by the RDB extractor). Run it again after re-extracting GameData:

    python Generate-PlayfieldNames.py
"""

import glob
import json
import os

ROOT = os.path.dirname(os.path.abspath(__file__))
PLAYFIELDS = os.path.join(ROOT, "..", "..", "..", "AORebirth", "GameData", "Playfields")
OUT = os.path.join(ROOT, "src", "playfield_names.inc")


def c_string(text):
    out = []
    for byte in text.encode("cp1252", errors="replace"):
        ch = chr(byte)
        if ch in "\\\"":
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


names = {}
for path in glob.glob(os.path.join(PLAYFIELDS, "*", "metadata.json")):
    folder = os.path.basename(os.path.dirname(path))
    if not folder.isdigit():
        continue
    with open(path, encoding="utf-8") as f:
        name = (json.load(f).get("playfieldName") or "").split("\0")[0].strip()
    if name:
        names[int(folder)] = name

with open(OUT, "w", encoding="ascii", newline="\n") as f:
    f.write("// Generated by Generate-PlayfieldNames.py from GameData/Playfields/*/metadata.json - do not edit.\n")
    f.write("// { playfield id, name }, sorted by id.\n")
    for playfield, name in sorted(names.items()):
        f.write("{ %d, %s },\n" % (playfield, c_string(name)))

print("%d playfield names -> %s" % (len(names), OUT))
