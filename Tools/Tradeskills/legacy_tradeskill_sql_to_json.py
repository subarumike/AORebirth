"""CellAO tradeskill table (tradeskill.sql) -> GameData/Tradeskills.Legacy.json.

The table is CellAO's community-collected recipe list: unverified against live, so ZoneEngine_New searches it only
after GameData/Tradeskills.json (captured and hand-checked recipes). Columns (see the CREATE TABLE in the .sql):

  Id1, Id2        source and target high ids          -> Source, Target
  ResultIds       "low,high"                          -> Result
  DeleteFlag      bit 0 source, bit 1 target          -> ConsumeSource, ConsumeTarget
  MinTarget       target must be at least this QL     -> MinTargetQl
  QlRangePercent  source QL may be this % below       -> QlRangePercent
  Skill / SkillPercent / SkillPerBump (comma lists)   -> Skills [{Stat, Percent, PerBump}] (stat 0 = none)
  MaxBump, MinXP, MaxXP, IsImplant                    -> MaxBump, MinXp, MaxXp, Implant (implants go either way)

Identical rows are kept once; when one pair has different rows, the first wins (as CellAO's lookup did).
With --items <tsv of id, ql, name> (dumped from items.dat) rows naming an item missing from items.dat are dropped.

    python -I legacy_tradeskill_sql_to_json.py [--sql ...] [--out ...] [--items items.tsv]
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
DEFAULT_SQL = os.path.join(ROOT, 'AORebirth', 'Libraries', 'Source', 'AORebirth.Database', 'SqlTables', 'tradeskill.sql')
DEFAULT_OUT = os.path.join(ROOT, 'AORebirth', 'GameData', 'Tradeskills.Legacy.json')

ROW = re.compile(r"INSERT INTO `tradeskill` VALUES \((-?\d+),(-?\d+),(-?\d+),'([^']*)',(-?\d+),(-?\d+),"
                 r"\"([^\"]*)\",\"([^\"]*)\",\"([^\"]*)\",(-?\d+),(-?\d+),(-?\d+),(-?\d+)\);")


def ints(text):
    return [int(x) for x in text.split(',') if x.strip().lstrip('-').isdigit()]


def recipe(row):
    id1, id2, min_target, result_ids, ql_range, delete_flag, skill, percent, per_bump, max_bump, min_xp, max_xp, implant = row
    result = ints(result_ids)
    if not result:
        return None
    stats, percents, bumps = ints(skill), ints(percent), ints(per_bump)
    skills = [{'Stat': s, 'Percent': percents[i] if i < len(percents) else 0, 'PerBump': bumps[i] if i < len(bumps) else 0}
              for i, s in enumerate(stats) if s > 0]
    r = {
        'Key': '%s>%s' % (id1, id2),
        'Source': [int(id1)], 'Target': [int(id2)],
        'Result': {'LowId': result[0], 'HighId': result[1] if len(result) > 1 else result[0]},
        'ConsumeSource': bool(int(delete_flag) & 1), 'ConsumeTarget': bool(int(delete_flag) & 2),
    }
    if int(implant):
        r['AnyOrder'] = True
        r['Implant'] = True
    for key, value in (('MinTargetQl', int(min_target)), ('QlRangePercent', int(ql_range)), ('MaxBump', int(max_bump)),
                       ('MinXp', int(min_xp)), ('MaxXp', int(max_xp))):
        if value:
            r[key] = value
    if skills:
        r['Skills'] = skills
    r['Provenance'] = 'cellao-tradeskill-sql'
    return r


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--sql', default=DEFAULT_SQL)
    ap.add_argument('--out', default=DEFAULT_OUT)
    ap.add_argument('--items', help='TSV of item id, ql, name from items.dat; drops rows naming unknown items')
    args = ap.parse_args()

    known = None
    if args.items:
        known = {int(line.split('\t', 1)[0]) for line in open(args.items, encoding='utf-8') if line.strip()}

    rows = seen = conflicts = unknown = bad = 0
    recipes, by_key = [], {}
    for line in open(args.sql, encoding='latin-1'):
        if not line.startswith('INSERT INTO'):
            continue
        rows += 1
        m = ROW.match(line.strip())
        r = recipe(m.groups()) if m else None
        if r is None:
            bad += 1
            continue
        if known is not None and any(i not in known for i in r['Source'] + r['Target'] + [r['Result']['LowId'], r['Result']['HighId']]):
            unknown += 1
            continue
        first = by_key.get(r['Key'])
        if first is not None:
            seen += 1
            if first != r:
                conflicts += 1
            continue
        by_key[r['Key']] = r
        recipes.append(r)

    with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('{"_comment": "Generated by Tools/Tradeskills/legacy_tradeskill_sql_to_json.py from the CellAO tradeskill table. '
                'Unverified against live; searched after Tradeskills.json. Do not edit by hand.",\n"Recipes": [\n')
        f.write(',\n'.join(json.dumps(r, separators=(',', ':')) for r in recipes))
        f.write('\n]}\n')

    print('%d rows: %d recipes, %d duplicates (%d of them differing; first kept), %d naming items not in items.dat, %d unreadable'
          % (rows, len(recipes), seen, conflicts, unknown, bad))
    print('wrote', args.out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
