	internal static MissionLocationSide ResolveTerminalSide(int playfieldId)
	{
		switch (playfieldId)
		{
		case 540:
		case 545:
		case 640:
		case 641:
		case 646:
		case 647:
		case 952:
		case 953:
			return MissionLocationSide.Clan;
		case 700:
		case 705:
		case 706:
		case 710:
		case 716:
		case 717:
		case 730:
		case 735:
		case 740:
		case 950:
			return MissionLocationSide.Omni;
		default:
			return MissionLocationSide.Neutral;
		}
	}

	internal static MissionLocationSide ResolveMarkerSide(int playfieldId)
	{
		switch (playfieldId)
		{
		case 545:
		case 550:
		case 551:
		case 585:
		case 586:
		case 600:
			return MissionLocationSide.Clan;
		case 635:
		case 650:
		case 655:
		case 665:
		case 670:
		case 685:
		case 695:
		case 696:
		case 760:
		case 790:
		case 791:
		case 795:
			return MissionLocationSide.Omni;
		default:
			return MissionLocationSide.Neutral;
		}
	}

	internal static bool IsSpotAllowedForTerminal(int markerPlayfieldId, MissionLocationSide terminalSide)
	{
		if (terminalSide == MissionLocationSide.Neutral)
		{
			return true;
		}
		MissionLocationSide missionLocationSide = ResolveMarkerSide(markerPlayfieldId);
		return missionLocationSide == MissionLocationSide.Neutral || missionLocationSide == terminalSide;
	}
